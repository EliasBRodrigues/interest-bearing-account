CREATE SEQUENCE IF NOT EXISTS numero_conta START WITH 100001 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS conta (
    id VARCHAR(36) PRIMARY KEY,
    numero VARCHAR(30) NOT NULL UNIQUE,
    titular VARCHAR(120) NOT NULL,
    senha_hash VARCHAR(100) NOT NULL,
    saldo DECIMAL(19,2) DEFAULT 0 NOT NULL CHECK (saldo >= 0),
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL);

CREATE TABLE IF NOT EXISTS sessao (
    token_hash VARCHAR(64) PRIMARY KEY,
    conta_id VARCHAR(36) NOT NULL REFERENCES conta(id),
    expira_em TIMESTAMP WITH TIME ZONE NOT NULL);

CREATE INDEX IF NOT EXISTS ix_sessao_expira ON sessao(expira_em);

CREATE TABLE IF NOT EXISTS lancamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id VARCHAR(36) NOT NULL REFERENCES conta(id),
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('DEPOSITO','SAQUE','JUROS')),
    valor DECIMAL(19,2) NOT NULL,
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL,
    data_fechamento DATE,
    UNIQUE (conta_id, data_fechamento),
    CHECK ((tipo = 'SAQUE' AND valor < 0) OR (tipo IN ('DEPOSITO','JUROS') AND valor > 0)));

CREATE INDEX IF NOT EXISTS ix_extrato ON lancamento(conta_id,data_hora DESC,id DESC);

CREATE TABLE IF NOT EXISTS configuracao (id INTEGER PRIMARY KEY CHECK (id=1), taxa_diaria DECIMAL(14,10));

INSERT INTO configuracao(id,taxa_diaria) SELECT 1,NULL WHERE NOT EXISTS (SELECT 1 FROM configuracao WHERE id=1);

CREATE TABLE IF NOT EXISTS fechamento (
    data DATE PRIMARY KEY,
    status VARCHAR(15) NOT NULL CHECK (status IN ('EM_ANDAMENTO','CONCLUIDO','ERRO')),
    contas_processadas BIGINT NOT NULL DEFAULT 0,
    iniciado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    concluido_em TIMESTAMP WITH TIME ZONE);

CREATE TABLE IF NOT EXISTS fechamento_conta (
    data DATE NOT NULL REFERENCES fechamento(data),
    conta_id VARCHAR(36) NOT NULL REFERENCES conta(id),
    processada BOOLEAN NOT NULL DEFAULT FALSE,
    taxa_aplicada DECIMAL(14,10),
    juros DECIMAL(19,2),
    PRIMARY KEY (data,conta_id));

CREATE INDEX IF NOT EXISTS ix_fechamento_pendente ON fechamento_conta(data,processada,conta_id);
